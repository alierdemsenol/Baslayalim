object TranslationHelper {

    fun getTranslation(key: String, lang: String): String {
        return if (lang.equals("TR", ignoreCase = true)) {
            trMap[key] ?: key
        } else {
            enMap[key] ?: trMap[key] ?: key
        }
    }

    fun localizeSubject(subject: String, lang: String): String {
        if (lang.equals("TR", ignoreCase = true)) return subject
        return subjectEnMap[subject] ?: subject
    }

    fun localizeTrack(track: String, lang: String): String {
        if (lang.equals("TR", ignoreCase = true)) return track
        return when (track) {
            "Sayısal" -> "STEM (Sci & Math)"
            "Eşit Ağırlık" -> "Equal Weight"
            "Sözel" -> "Verbal"
            "Dil" -> "Language"
            "LGS Genel" -> "LGS General"
            "KPSS Genel" -> "KPSS General"
            else -> track
        }
    }

    fun localizeDenemeOption(option: String, lang: String): String {
        if (lang.equals("TR", ignoreCase = true)) return option
        if (option.contains("Branş Denemesi - ")) {
            val parts = option.split("Branş Denemesi - ", limit = 2)
            val prefixStage = parts[0].trim()
            val rawSubj = parts.getOrNull(1)?.trim() ?: ""
            val locSubj = localizeSubject(rawSubj, lang)
            return if (prefixStage.isNotBlank()) "$prefixStage Subject Mock - $locSubj" else "Subject Mock - $locSubj"
        }
        return when (option) {
            "TYT Deneme Sınavı (165 dk)" -> "TYT Mock Exam (165 min)"
            "AYT Deneme Sınavı (180 dk)" -> "AYT Mock Exam (180 min)"
            "YDT Deneme Sınavı (120 dk)" -> "YDT Mock Exam (120 min)"
            "LGS Sözel (75 dk)" -> "LGS Verbal (75 min)"
            "LGS Sayısal (80 dk)" -> "LGS Numerical (80 min)"
            "LGS Genel Deneme (155 dk)" -> "LGS Full Mock (155 min)"
            "KPSS Genel Yetenek - Genel Kültür (130 dk)" -> "KPSS General Aptitude & Culture (130 min)"
            "KPSS Eğitim Bilimleri (100 dk)" -> "KPSS Educational Sciences (100 min)"
            "KPSS Alan Bilgisi (150 dk)" -> "KPSS Field Knowledge (150 min)"
            else -> option
        }
    }

    fun localizeMood(mood: String, lang: String): String {
        if (lang.equals("TR", ignoreCase = true)) return mood
        return moodEnMap[mood] ?: mood
    }

